import {readFile,writeFile} from 'node:fs/promises';
import {gzipSync} from 'node:zlib';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../dist');
// Browser modules are wrapped separately, keeping their scopes. No runtime loader,
// local fetch, or external build dependency is needed when opening index.html.
export async function buildStatic(){
 const names=['core.mjs','catalogue.mjs','river.mjs','profile.mjs','profile-view.mjs','station-layer.mjs','map-background.mjs','app.js'];
 let bundle="/* Generated by scripts/build-static.mjs */\n(()=>{const modules={};\n";
 for(const name of names){
  let source=await readFile(path.join(root,name),'utf8');
  const exports=[...source.matchAll(/export\s+(?:async\s+)?(?:function|const|class|let)\s+(\w+)/g)].map(m=>m[1]);
  source=source.replace(/import\s*\{([^}]+)\}\s*from\s*['"]\.\/([^'"]+)['"];?/g,(_,items,dependency)=>`const {${items}}=modules[${JSON.stringify(dependency)}];`);
  source=source.replace(/\bexport\s+(?=(?:async\s+)?(?:function|const|class|let)\s)/g,'');
  if(/^\s*import\s/m.test(source))throw Error(`Unresolved import in ${name}`);
  bundle+=`modules[${JSON.stringify(name)}]=(()=>{\n${source}\nreturn {${exports.join(',')}};\n})();\n`;
 }
 bundle+='})();\n';
 const data={};
 for(const [key,name] of Object.entries({catalogue:'stations.compact.json',examples:'examples.json',departments:'departments.geojson',coverage:'coverage.json',rivers:'rivers.json'})){
  try{data[key]=JSON.parse(await readFile(path.join(root,'data',name),'utf8'));}catch(e){if(e.code!=='ENOENT')throw e;if(key==='catalogue')throw e;data[key]=null;}
 }
 if(data.coverage?.complete){
  const source=data.coverage,codes=source.parameters.map(p=>String(p.code)),bits=new Map(codes.map((code,i)=>[code,2**i]));
  const compact=stations=>Object.fromEntries(Object.entries(stations).map(([id,list])=>[id,list.reduce((mask,code)=>mask|(bits.get(String(code))||0),0)]));
  data.coverage={retrievedAt:source.retrievedAt,source:source.source,support:source.support,qualification:source.qualification,complete:true,codes,stations:compact(source.stations),recent:source.recent?.complete===false?null:(source.recent?{start:source.recent.start,end:source.recent.end,stations:compact(source.recent.stations)}:null)};
 }else data.coverage=null;
 const bootstrap='/* Local data snapshot; generated, do not edit. */\nglobalThis.RIVER_BOOT_DATA='+JSON.stringify(data)+';\n';
 for(const [name,source] of [['app.bundle.js',bundle],['data/bootstrap.js',bootstrap]]){
  await writeFile(path.join(root,name),source);await writeFile(path.join(root,name+'.gz'),gzipSync(source,{level:9}));
 }
 console.log(JSON.stringify({classicBundleBytes:Buffer.byteLength(bundle),bootstrapBytes:Buffer.byteLength(bootstrap),gzipBytes:gzipSync(bootstrap,{level:9}).length,fileOpeningSupported:true}));
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await buildStatic();
